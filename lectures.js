/* ===== Lecture UI ===== */
const lecBox = $('#lec-box');
let lecPath = [], lecIdx = 0;

function lecEmbed(url) {
  const u = String(url || '').trim();
  if (!u) return null;
  const pl = u.match(/[?&]list=([\w-]+)/);
  const vid = u.match(/(?:v=|youtu\.be\/|embed\/|shorts\/|live\/)([\w-]{11})/) || (/^[\w-]{11}$/.test(u) ? [0, u] : null);
  if (vid) return 'https://www.youtube-nocookie.com/embed/' + vid[1] + '?rel=0&modestbranding=1' + (pl ? '&list=' + pl[1] : '');
  if (pl) return 'https://www.youtube-nocookie.com/embed/videoseries?list=' + pl[1];
  return null;
}

const lecNodeAt = path => path.reduce((n, k) => n[k], LECTURES);
const lecPlayable = n => typeof n === 'string' || Array.isArray(n);

function lecGoto(path) { lecPath = path; lecIdx = 0; lecRender(); }

function lecCrumbs() {
  const kids = [];
  ['All classes'].concat(lecPath).forEach((label, i) => {
    if (i) kids.push(h('span', { class: 'sep', text: '\u203A' }));
    kids.push(h('button', { type: 'button', text: label, onclick: () => lecGoto(lecPath.slice(0, i)) }));
  });
  return h('div', { class: 'lec-crumbs' }, kids);
}

function lecTitle(n) {
  if (!lecPath.length) return 'Select your class';
  if (lecPath.length === 1) return 'Select your board';
  const vals = Object.values(n);
  if (vals.some(v => v && typeof v === 'object' && !Array.isArray(v) && Object.values(v).some(x => !Array.isArray(x)))) return 'Select your stream';
  if (vals.every(Array.isArray)) return 'Select a chapter';
  return 'Select a subject';
}


/* ===== Playlist player: shows every episode so you can pick any ===== */
let lecPlayer = null, lecTok = 0, lecApi = null;
const lecListId = url => { const m = String(url || '').match(/[?&]list=([\w-]+)/); return m ? m[1] : null; };

function lecLoadApi() {
  if (lecApi) return lecApi;
  lecApi = new Promise(res => {
    if (window.YT && window.YT.Player) return res();
    const prev = window.onYouTubeIframeAPIReady;
    window.onYouTubeIframeAPIReady = () => { if (prev) prev(); res(); };
    const s = document.createElement('script');
    s.src = 'https://www.youtube.com/iframe_api';
    document.head.append(s);
  });
  return lecApi;
}

function lecKill() {
  lecTok++;
  if (lecPlayer) { try { lecPlayer.destroy(); } catch (e) {} lecPlayer = null; }
}

function lecMark(p) {
  let i = -1;
  try { i = p.getPlaylistIndex(); } catch (e) {}
  const box = $('#lec-eps');
  if (!box) return;
  box.querySelectorAll('.lec-item').forEach((b, k) => b.classList.toggle('active', k === i));
  const on = box.querySelector('.lec-item.active');
  if (on) box.scrollTop = on.offsetTop - box.offsetTop - 8;
}

function lecEpisodes(p, tok, tries = 0) {
  if (tok !== lecTok) return;
  const box = $('#lec-eps');
  if (!box) return;
  let ids = [];
  try { ids = p.getPlaylist() || []; } catch (e) {}
  if (!ids.length) {
    if (tries < 8) setTimeout(() => lecEpisodes(p, tok, tries + 1), 700);
    else fill(box, h('p', { class: 'muted small', text: 'Could not load the episode list. Use the next/previous buttons in the player.' }));
    return;
  }
  const btns = ids.map((id, i) => h('button', { class: 'lec-item', type: 'button', text: (i + 1) + '. Episode ' + (i + 1), onclick: () => { p.playVideoAt(i); } }));
  fill(box, btns);
  lecMark(p);
  let next = 0;
  const worker = async () => {
    while (next < ids.length && tok === lecTok) {
      const i = next++;
      try {
        const r = await fetch('https://www.youtube.com/oembed?format=json&url=' + encodeURIComponent('https://www.youtube.com/watch?v=' + ids[i]));
        const d = await r.json();
        if (d && d.title) btns[i].textContent = (i + 1) + '. ' + d.title;
      } catch (e) {}
    }
  };
  for (let k = 0; k < 4; k++) worker();
}

async function lecMount(listId) {
  const tok = ++lecTok;
  await lecLoadApi();
  if (tok !== lecTok || !$('#lec-yt')) return;
  lecPlayer = new YT.Player('lec-yt', {
    width: '100%', height: '100%',
    playerVars: { listType: 'playlist', list: listId, rel: 0, modestbranding: 1, playsinline: 1 },
    events: { onReady: e => lecEpisodes(e.target, tok), onStateChange: e => lecMark(e.target) }
  });
}

function lecRender() {
  if (!lecBox) return;
  lecKill();
  const n = lecNodeAt(lecPath);
  const out = [];
  if (lecPath.length) out.push(lecCrumbs());

  if (!lecPlayable(n)) {
    out.push(h('p', { class: 'lec-step', text: lecTitle(n) }),
      h('div', { class: 'grid3' }, Object.keys(n).map(k =>
        h('button', { class: 'lec-pick', type: 'button', onclick: () => lecGoto(lecPath.concat(k)) },
          h('span', { text: k }),
          Array.isArray(n[k]) ? h('small', { text: n[k].length + (n[k].length === 1 ? ' lecture' : ' lectures') }) : null))));
  } else {
    const name = lecPath[lecPath.length - 1];
    const list = typeof n === 'string' ? [{ title: name + ' - Full Playlist', url: n }] : n;
    const cur = list[lecIdx] || list[0];
    const pid = cur && lecListId(cur.url);
    const asPlaylist = !!pid && list.length === 1;
    const src = cur && lecEmbed(cur.url);
    const player = h('div', { class: 'lec-player' });
    if (asPlaylist) {
      player.append(h('div', { id: 'lec-yt' }));
    } else if (src) {
      player.append(h('iframe', {
        src, title: cur.title, loading: 'lazy', allowfullscreen: true,
        allow: 'accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; fullscreen',
        referrerpolicy: 'strict-origin-when-cross-origin'
      }));
    } else {
      player.append(h('div', { class: 'lec-soon' }, h('div', {}, h('strong', { text: 'Lecture coming soon' }), h('p', { class: 'small', text: 'No video link added yet.' }))));
    }
    let side = null;
    if (asPlaylist) {
      side = h('div', { class: 'card' }, h('h3', { text: 'Episodes' }),
        h('div', { class: 'lec-list', id: 'lec-eps' }, h('p', { class: 'muted small', text: 'Loading episodes…' })));
    } else if (list.length > 1) {
      side = h('div', { class: 'card' }, h('h3', { text: 'Lectures' }),
        h('div', { class: 'lec-list' }, list.map((l, i) =>
          h('button', { class: 'lec-item' + (i === lecIdx ? ' active' : ''), type: 'button', text: l.title, onclick: () => { lecIdx = i; lecRender(); } }))));
    }
    out.push(h('div', { class: side ? 'lec-layout' : '' },
      h('div', {}, player, h('h3', { text: asPlaylist ? name : (cur ? cur.title : '') }), h('p', { class: 'muted small', text: lecPath.join(' \u00B7 ') })),
      side));
    if (asPlaylist) setTimeout(() => lecMount(pid), 0);
  }
  fill(lecBox, out);
}

lecRender();